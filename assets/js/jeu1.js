function _launchRadar() {
    radarPhase = true;
    radarGameOver = false;
    radarWin = false;
    radarCollected = 0;
    radarCurrentTarget = 0;
    radarTargets = [];
    radarTimerStart = Date.now();
    radarSweepAngle = 0;
    radarFlash = 0;
    currentPos = null;
    geoError = null;
    lastBeepDist = 99999;

    canvas.style.display = 'none';
    radarCanvas.style.display = 'block';
    document.getElementById('pigeon-pause-btn').style.display = 'none';
    document.getElementById('radar-pause-btn').style.display = 'flex';
    document.getElementById('radar-skip-target-btn').style.display = 'block';

    updateTimerBar(1);
    document.getElementById('hp-fill').setAttribute('width', '0');

    if ('geolocation' in navigator) {
        watchId = navigator.geolocation.watchPosition(
            pos => {
                currentPos = { lat: pos.coords.latitude, lng: pos.coords.longitude };
                if (radarTargets.length === 0) {
                    radarTargets = generateRadarTargets(currentPos.lat, currentPos.lng);
                }
            },
            err => { geoError = err.message; },
            { enableHighAccuracy: true, maximumAge: 0, timeout: 5000 }
        );
    } else {
        geoError = 'GPS non disponible sur cet appareil.';
    }

    scheduleBeep();
}

/**
 * Logique de la partie radar à chaque frame :
 * mise à jour du timer, calcul de distance, détection de collecte.
 */
function updateRadar() {
    if (!radarPhase || radarGameOver || radarWin || radarPaused) return;

    const elapsed = Date.now() - radarTimerStart;
    const ratio = Math.max(0, 1 - elapsed / RADAR_TIMER);
    updateTimerBar(ratio);

    if (ratio === 0) {
        radarGameOver = true;
        stopBeeps();
        stopGeo();
        return;
    }

    radarSweepAngle = (radarSweepAngle + 1.8) % 360;

    if (!currentPos || radarTargets.length === 0) return;

    const target = radarTargets[radarCurrentTarget];
    const dist = haversine(currentPos.lat, currentPos.lng, target.lat, target.lng);
    lastBeepDist = dist;

    if (radarFlash > 0) radarFlash--;

    if (dist <= COLLECT_RADIUS) {
        playCollectSound();
        radarCollected++;
        radarFlash = 50;
        radarTimerStart = Date.now() - (RADAR_TIMER - 60000);

        const hpFill = document.getElementById('hp-fill');
        if (hpFill) hpFill.setAttribute('width', ((radarCollected / TOTAL_TARGETS) * HP_BAR_MAX_W).toFixed(1));

        if (radarCollected >= TOTAL_TARGETS) {
            radarWin = true;
            stopBeeps();
            stopGeo();
            return;
        }
        radarCurrentTarget++;
    }
}

/**
 * Dessine l'interface radar : fond sombre, cercle vert animé,
 * balayage rotatif, blip de la cible, distance et infos en bas.
 */
function drawRadar() {
    const w = radarCanvas.width;
    const h = radarCanvas.height;
    rctx.clearRect(0, 0, w, h);

    rctx.fillStyle = 'rgba(0, 8, 4, 0.92)';
    rctx.fillRect(0, 0, w, h);

    const cx = w / 2;
    const cy = h * 0.46;
    const R = Math.min(w, h) * 0.36;

    rctx.save();
    rctx.beginPath();
    rctx.arc(cx, cy, R, 0, Math.PI * 2);
    rctx.clip();

    rctx.fillStyle = '#010f07';
    rctx.fillRect(cx - R, cy - R, R * 2, R * 2);

    [0.25, 0.5, 0.75, 1].forEach(s => {
        rctx.beginPath();
        rctx.arc(cx, cy, R * s, 0, Math.PI * 2);
        rctx.strokeStyle = 'rgba(0, 200, 80, 0.18)';
        rctx.lineWidth = 1;
        rctx.stroke();
    });

    rctx.strokeStyle = 'rgba(0, 200, 80, 0.12)';
    rctx.lineWidth = 1;
    [-1, 1].forEach(d => {
        rctx.beginPath(); rctx.moveTo(cx, cy - R); rctx.lineTo(cx, cy + R); rctx.stroke();
        rctx.beginPath(); rctx.moveTo(cx - R, cy); rctx.lineTo(cx + R, cy); rctx.stroke();
    });

    const sweepRad = (radarSweepAngle - 90) * Math.PI / 180;
    const trailRad = 50 * Math.PI / 180;

    rctx.beginPath();
    rctx.moveTo(cx, cy);
    rctx.arc(cx, cy, R, sweepRad - trailRad, sweepRad, false);
    rctx.closePath();
    const trailGrad = rctx.createRadialGradient(cx, cy, 0, cx, cy, R);
    trailGrad.addColorStop(0, 'rgba(0, 255, 100, 0.18)');
    trailGrad.addColorStop(1, 'rgba(0, 255, 100, 0.04)');
    rctx.fillStyle = trailGrad;
    rctx.fill();

    rctx.save();
    rctx.strokeStyle = 'rgba(60, 255, 130, 0.95)';
    rctx.lineWidth = 2;
    rctx.shadowColor = 'rgba(60, 255, 130, 0.9)';
    rctx.shadowBlur = 8;
    rctx.beginPath();
    rctx.moveTo(cx, cy);
    rctx.lineTo(cx + Math.cos(sweepRad) * R, cy + Math.sin(sweepRad) * R);
    rctx.stroke();
    rctx.restore();

    if (currentPos && radarTargets.length > 0 && !radarGameOver && !radarWin) {
        const target = radarTargets[radarCurrentTarget];
        const dist = haversine(currentPos.lat, currentPos.lng, target.lat, target.lng);
        const tBearing = bearingTo(currentPos.lat, currentPos.lng, target.lat, target.lng);
        const relBearing = (tBearing - compassHeading + 360) % 360;
        const relRad = (relBearing - 90) * Math.PI / 180;
        const scale = Math.min(1, dist / MAX_RADAR_RANGE);
        const bx = cx + Math.cos(relRad) * scale * R;
        const by = cy + Math.sin(relRad) * scale * R;

        const pulse = 0.5 + 0.5 * Math.sin(Date.now() / 180);
        rctx.save();
        rctx.shadowColor = 'rgba(255, 240, 0, 0.9)';
        rctx.shadowBlur = 12 + pulse * 6;
        rctx.fillStyle = `rgba(255, 230, 0, ${0.75 + pulse * 0.25})`;
        rctx.beginPath();
        rctx.arc(bx, by, 5 + pulse * 2.5, 0, Math.PI * 2);
        rctx.fill();
        rctx.restore();
    }

    if (radarFlash > 0) {
        rctx.fillStyle = `rgba(0, 255, 120, ${(radarFlash / 50) * 0.35})`;
        rctx.fillRect(cx - R, cy - R, R * 2, R * 2);
    }

    rctx.restore();

    rctx.save();
    rctx.strokeStyle = 'rgba(0, 220, 80, 0.7)';
    rctx.lineWidth = 2.5;
    rctx.shadowColor = 'rgba(0, 220, 80, 0.5)';
    rctx.shadowBlur = 10;
    rctx.beginPath();
    rctx.arc(cx, cy, R, 0, Math.PI * 2);
    rctx.stroke();
    rctx.restore();

    rctx.fillStyle = 'rgba(0, 220, 80, 0.9)';
    rctx.font = 'bold 11px monospace';
    rctx.textAlign = 'center';
    rctx.textBaseline = 'middle';
    rctx.fillText('N', cx, cy - R + 12);
    rctx.fillText('S', cx, cy + R - 12);
    rctx.fillText('E', cx + R - 10, cy);
    rctx.fillText('O', cx - R + 10, cy);

    rctx.fillStyle = 'rgba(0, 200, 80, 0.6)';
    rctx.beginPath();
    rctx.arc(cx, cy, 4, 0, Math.PI * 2);
    rctx.fill();

    const infoY = cy + R + 24;
    rctx.textAlign = 'center';
    rctx.textBaseline = 'top';

    if (geoError) {
        rctx.fillStyle = '#ff6060';
        rctx.font = 'bold 14px monospace';
        rctx.fillText('GPS indisponible', cx, infoY);
        rctx.fillStyle = '#aaa';
        rctx.font = '11px monospace';
        rctx.fillText(geoError, cx, infoY + 20);
    } else if (!currentPos) {
        rctx.fillStyle = '#00dc50';
        rctx.font = 'bold 15px monospace';
        rctx.fillText('Recherche GPS...', cx, infoY);
    } else {
        const target = radarTargets[radarCurrentTarget];
        const dist = haversine(currentPos.lat, currentPos.lng, target.lat, target.lng);
        const distStr = dist < 1000 ? `${Math.round(dist)} m` : `${(dist / 1000).toFixed(2)} km`;

        rctx.fillStyle = '#00dc50';
        rctx.font = 'bold 22px monospace';
        rctx.fillText(distStr, cx, infoY);

        rctx.fillStyle = 'rgba(0, 200, 80, 0.7)';
        rctx.font = '14px monospace';
        rctx.fillText(`Cibles : ${radarCollected} / ${TOTAL_TARGETS}`, cx, infoY + 32);
    }

    if (radarGameOver) {
        rctx.fillStyle = 'rgba(0,0,0,0.65)';
        rctx.fillRect(0, 0, w, h);
        rctx.fillStyle = '#FFD700';
        rctx.font = 'bold 38px monospace';
        rctx.textAlign = 'center';
        rctx.textBaseline = 'middle';
        rctx.fillText(t('radar.gameover-title'), w / 2, h / 2 - 30);
        rctx.fillStyle = '#fff';
        rctx.font = '18px monospace';
        rctx.fillText(t('radar.gameover-retry'), w / 2, h / 2 + 20);
    }

    if (radarWin) {
        rctx.fillStyle = 'rgba(0,0,0,0.65)';
        rctx.fillRect(0, 0, w, h);
        rctx.fillStyle = '#00ff80';
        rctx.font = 'bold 38px monospace';
        rctx.textAlign = 'center';
        rctx.textBaseline = 'middle';
        rctx.fillText(t('radar.win-title'), w / 2, h / 2 - 40);
        rctx.fillStyle = '#fff';
        rctx.font = '20px monospace';
        rctx.fillText(t('radar.win-sub'), w / 2, h / 2 + 10);
        rctx.font = '15px monospace';
        rctx.fillStyle = 'rgba(255,255,255,0.7)';
        rctx.fillText(t('radar.win-replay'), w / 2, h / 2 + 50);
    }
}

/**
 * Met le radar sur pause : fige le timer, coupe les bips,
 * ouvre le menu qui glisse depuis la droite.
 */
function pauseRadar() {
    if (!radarPhase || radarGameOver || radarWin || radarPaused) return;
    radarPaused = true;
    radarPauseStamp = Date.now();
    stopBeeps();
    document.getElementById('radar-pause-menu').classList.add('open');
}

/**
 * Reprend le radar : compense le temps passé en pause dans le timer,
 * relance les bips et ferme le menu.
 */
function resumeRadar() {
    if (!radarPaused) return;
    radarTimerStart += Date.now() - radarPauseStamp;
    radarPaused = false;
    document.getElementById('radar-pause-menu').classList.remove('open');
    scheduleBeep();
}

function winRadar() {
    document.getElementById('radar-pause-menu').classList.remove('open');
    radarWin = true;
    stopBeeps();
    stopGeo();
}

