const radarCanvas = document.getElementById('radarCanvas');
const rctx = radarCanvas.getContext('2d');

const COLLECT_RADIUS = 3;
const MAX_RADAR_RANGE = 20;
const RADAR_TIMER = 60000;
const TOTAL_TARGETS = 3;

let radarGameOver = false;
let radarWin = false;
let radarPaused = false;
let radarPauseStamp = 0;
let radarTimerStart = 0;
let radarTargets = [];
let radarCurrentTarget = 0;
let radarCollected = 0;
let radarSweepAngle = 0;
let radarFlash = 0;
let currentPos = null;
let geoError = null;
let watchId = null;
let audioCtx = null;
let beepTimeout = null;
let lastBeepDist = 99999;


/**
 * Calcule la distance en mètres entre deux coordonnées GPS
 * via la formule de Haversine. Suffisamment précis pour quelques centaines de mètres.
 * @param {number} lat1 @param {number} lng1 @param {number} lat2 @param {number} lng2
 * @returns {number} Distance en mètres.
 */
function haversine(lat1, lng1, lat2, lng2) {
    const R = 6371000;
    const p1 = lat1 * Math.PI / 180;
    const p2 = lat2 * Math.PI / 180;
    const dp = (lat2 - lat1) * Math.PI / 180;
    const dl = (lng2 - lng1) * Math.PI / 180;
    const a = Math.sin(dp / 2) ** 2 + Math.cos(p1) * Math.cos(p2) * Math.sin(dl / 2) ** 2;
    return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/**
 * Calcule le cap (bearing) en degrés du point 1 vers le point 2.
 * 0° = Nord, 90° = Est, sens horaire.
 * @param {number} lat1 @param {number} lng1 @param {number} lat2 @param {number} lng2
 * @returns {number} Cap en degrés [0, 360[.
 */
function bearingTo(lat1, lng1, lat2, lng2) {
    const p1 = lat1 * Math.PI / 180;
    const p2 = lat2 * Math.PI / 180;
    const dl = (lng2 - lng1) * Math.PI / 180;
    const y = Math.sin(dl) * Math.cos(p2);
    const x = Math.cos(p1) * Math.sin(p2) - Math.sin(p1) * Math.cos(p2) * Math.cos(dl);
    return (Math.atan2(y, x) * 180 / Math.PI + 360) % 360;
}

/**
 * Génère 3 cibles GPS autour de la position de départ du joueur,
 * espacées d'environ 8 à 15 mètres, réparties à 120° les unes des autres.
 * @param {number} baseLat - Latitude de départ.
 * @param {number} baseLng - Longitude de départ.
 * @returns {Array} Tableau de 3 objets { lat, lng }.
 */
function generateRadarTargets(baseLat, baseLng) {
    const cosLat = Math.cos(baseLat * Math.PI / 180);
    return [0, 1, 2].map(i => {
        const angle = (i * 120 + Math.random() * 60 - 30) * Math.PI / 180;
        const dist = 8 + Math.random() * 7;
        return {
            lat: baseLat + (dist / 111320) * Math.cos(angle),
            lng: baseLng + (dist / (111320 * cosLat)) * Math.sin(angle)
        };
    });
}

/**
 * Retourne ou crée l'AudioContext partagé.
 * Le crée en lazy pour respecter la politique des navigateurs
 * (doit suivre une interaction utilisateur).
 * @returns {AudioContext}
 */
function getAudioCtx() {
    if (!audioCtx) audioCtx = new (window.AudioContext || window.webkitAudioContext)();
    return audioCtx;
}

/**
 * Joue un bip radar court avec un léger pitch descendant,
 * comme un vrai sonar. Fréquence plus haute = cible plus proche.
 * @param {number} [freq=880] - Fréquence de base en Hz.
 */
function playBeep(freq = 880) {
    const ac = getAudioCtx();
    const osc = ac.createOscillator();
    const gain = ac.createGain();
    osc.connect(gain);
    gain.connect(ac.destination);
    osc.type = 'sine';
    osc.frequency.setValueAtTime(freq, ac.currentTime);
    osc.frequency.exponentialRampToValueAtTime(freq * 0.65, ac.currentTime + 0.09);
    gain.gain.setValueAtTime(0.35, ac.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ac.currentTime + 0.1);
    osc.start(ac.currentTime);
    osc.stop(ac.currentTime + 0.12);
}

/**
 * Joue un petit jingle de victoire (arpège montant) quand on
 * collecte une cible. Court et satisfaisant.
 */
function playCollectSound() {
    const ac = getAudioCtx();
    [440, 554, 659, 880].forEach((f, i) => {
        const osc = ac.createOscillator();
        const gain = ac.createGain();
        osc.connect(gain);
        gain.connect(ac.destination);
        osc.frequency.value = f;
        osc.type = 'sine';
        const t = ac.currentTime + i * 0.1;
        gain.gain.setValueAtTime(0.3, t);
        gain.gain.exponentialRampToValueAtTime(0.001, t + 0.15);
        osc.start(t);
        osc.stop(t + 0.18);
    });
}

/**
 * Donne l'intervalle en ms entre deux bips selon la distance.
 * Plus on est proche, plus ça bipe vite. À 15m : mode panique.
 * @param {number} dist - Distance en mètres.
 * @returns {number} Intervalle en millisecondes.
 */
function beepInterval(dist) {
    if (dist > 200) return 3000;
    if (dist > 120) return 2000;
    if (dist > 70) return 1100;
    if (dist > 35) return 550;
    if (dist > COLLECT_RADIUS) return 220;
    return 100;
}

/**
 * Programme le prochain bip radar en fonction de la distance actuelle.
 * Se rappelle toute seule jusqu'à ce qu'on arrête tout.
 */
function scheduleBeep() {
    if (!radarPhase || radarGameOver || radarWin) return;
    const dist = lastBeepDist;
    const freq = dist < 10 ? 1100 : dist < 20 ? 990 : 880;
    playBeep(freq);
    beepTimeout = setTimeout(scheduleBeep, beepInterval(dist));
}

/**
 * Arrête les bips en cours et annule le timeout planifié.
 */
function stopBeeps() {
    if (beepTimeout) { clearTimeout(beepTimeout); beepTimeout = null; }
}

/**
 * Arrête le suivi GPS et libère les ressources associées.
 */
function stopGeo() {
    if (watchId !== null) { navigator.geolocation.clearWatch(watchId); watchId = null; }
}

