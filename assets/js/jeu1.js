/**
 * Calcule toute la logique du jeu à chaque frame :
 * déplacement du pigeon, comportement du NPC, physique des
 * projectiles et détection des collisions.
 */
function update() {
    if (!gameStarted || gameOver || pigeonPaused) return;

    const elapsed = Date.now() - timerStart;
    const ratio = Math.max(0, 1 - elapsed / TIMER_DURATION);
    updateTimerBar(ratio);
    if (ratio === 0) {
        gameOver = true;
        return;
    }

    let effectiveTilt = tiltX;
    if (keys['ArrowLeft'] || keys['a'] || keys['A']) effectiveTilt -= 45;
    if (keys['ArrowRight'] || keys['d'] || keys['D']) effectiveTilt += 45;
    pigeon.vx += (effectiveTilt / 45) * 0.7;
    pigeon.vx *= 0.87;
    pigeon.vx = Math.max(-MAX_SPEED, Math.min(MAX_SPEED, pigeon.vx));
    pigeon.x += pigeon.vx;
    pigeon.x = Math.max(0, Math.min(canvas.width - PIGEON_W, pigeon.x));

    const now = Date.now();
    if (now - lastNpcDir > 300 + Math.random() * 400) {
        const roll = Math.random();
        if (roll < 0.08) {
            npc.vx = 0;
        } else if (roll < 0.55) {
            npc.vx = 0.8 + Math.random() * 1.2;
        } else {
            npc.vx = -(0.8 + Math.random() * 1.2);
        }
        lastNpcDir = now;
    }

    npc.x += npc.vx;
    if (npc.x < 0) { npc.x = 0; npc.vx = Math.abs(npc.vx); }
    if (npc.x + NPC_W > canvas.width) { npc.x = canvas.width - NPC_W; npc.vx = -Math.abs(npc.vx); }

    if (hitFlash > 0) hitFlash--;

    for (let i = poops.length - 1; i >= 0; i--) {
        const p = poops[i];
        p.vy += GRAVITY;
        p.x += p.vx;
        p.y += p.vy;

        if (p.x < npc.x + NPC_W && p.x + POOP_W > npc.x &&
            p.y < npc.y + NPC_H && p.y + POOP_H > npc.y) {
            hp = Math.max(0, hp - 20);
            updateHPBar();
            hitFlash = 8;
            poops.splice(i, 1);
            if (hp <= 0) {
                startRadarPhase();
                return;
            }
            continue;
        }

        if (p.y > canvas.height + 60 || p.x < -60 || p.x > canvas.width + 60) {
            poops.splice(i, 1);
        }
    }
}

/**
 * Dessine tout ce qui est visible : pigeon, NPC, projectiles,
 * ombre projetée, et l'écran de game over si besoin.
 */
function draw() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    if (bgImage.complete && bgImage.naturalWidth > 0)
        ctx.drawImage(bgImage, 0, 0, canvas.width, canvas.height);
    const splitY = canvas.height * ZONE_SPLIT;
    if (!gameStarted) return;

    const shadowY = splitY - 6;
    const shadowScale = Math.max(0.2, 1 - (shadowY - pigeon.y) / (splitY - SVG_BOTTOM));
    ctx.save();
    ctx.globalAlpha = 0.18 * shadowScale;
    ctx.fillStyle = '#000';
    ctx.beginPath();
    ctx.ellipse(pigeon.x + PIGEON_W / 2, shadowY, PIGEON_W * 0.5 * shadowScale, 6 * shadowScale, 0, 0, Math.PI * 2);
    ctx.fill();
    ctx.restore();

    // ── Pigeon sprite ──
    const pFrame = Math.floor(Date.now() / 120) % 4;
    const pSrcX = pFrame * 223;
    const pDispW = 64, pDispH = 80;
    const pDrawX = pigeon.x - (pDispW - PIGEON_W) / 2;
    const pDrawY = pigeon.y - (pDispH - PIGEON_H) / 2;
    ctx.save();
    ctx.imageSmoothingEnabled = false;
    if (pigeonSprite.complete && pigeonSprite.naturalWidth > 0) {
        if (pigeon.vx < 0) {
            ctx.translate(pDrawX + pDispW, pDrawY);
            ctx.scale(-1, 1);
            ctx.drawImage(pigeonSprite, pSrcX, 0, 223, 279, 0, 0, pDispW, pDispH);
        } else {
            ctx.drawImage(pigeonSprite, pSrcX, 0, 223, 279, pDrawX, pDrawY, pDispW, pDispH);
        }
    } else {
        ctx.fillStyle = '#b4cde8';
        ctx.fillRect(pigeon.x, pigeon.y, PIGEON_W, PIGEON_H);
    }
    ctx.restore();

    ctx.save();
    ctx.setLineDash([4, 6]);
    ctx.strokeStyle = 'rgba(255,255,255,0.35)';
    ctx.lineWidth = 1.5;
    ctx.beginPath();
    ctx.moveTo(pigeon.x + PIGEON_W / 2, pigeon.y + PIGEON_H);
    ctx.lineTo(pigeon.x + PIGEON_W / 2, splitY);
    ctx.stroke();
    ctx.restore();

    // ── Lehmann (NPC) sprite ──
    const isWalking = Math.abs(npc.vx) > 0.1;
    const bSrcY = isWalking ? 52 : 4;
    const bFrameCount = isWalking ? 7 : 8;
    const bFps = isWalking ? 14 : 8;
    const bFrame = Math.floor(Date.now() / (1000 / bFps)) % bFrameCount;
    const bSrcX = bFrame * BENNER_FRAME_W;
    const bDispW = BENNER_FRAME_W * 3, bDispH = BENNER_FRAME_H * 3;
    const bDrawX = npc.x + (NPC_W - bDispW) / 2;
    const bDrawY = npc.y + NPC_H - bDispH;
    ctx.save();
    ctx.imageSmoothingEnabled = false;
    if (hitFlash > 0) { ctx.filter = 'brightness(3) saturate(0)'; }
    if (bennerSprite.complete && bennerSprite.naturalWidth > 0) {
        if (npc.vx < 0) {
            ctx.translate(bDrawX + bDispW, bDrawY);
            ctx.scale(-1, 1);
            ctx.drawImage(bennerSprite, bSrcX, bSrcY, BENNER_FRAME_W, BENNER_FRAME_H, 0, 0, bDispW, bDispH);
        } else {
            ctx.drawImage(bennerSprite, bSrcX, bSrcY, BENNER_FRAME_W, BENNER_FRAME_H, bDrawX, bDrawY, bDispW, bDispH);
        }
    } else {
        ctx.fillStyle = hitFlash > 0 ? '#ff3030' : '#e8863a';
        ctx.fillRect(npc.x, npc.y, NPC_W, NPC_H);
    }
    ctx.restore();

    for (const p of poops) {
        ctx.save();
        ctx.imageSmoothingEnabled = false;
        if (poopSprite.complete && poopSprite.naturalWidth > 0) {
            const pDispW = 32, pDispH = 32;
            ctx.drawImage(poopSprite, p.x - (pDispW - POOP_W) / 2, p.y - (pDispH - POOP_H) / 2, pDispW, pDispH);
        } else {
            ctx.fillStyle = '#7b4220';
            ctx.fillRect(p.x, p.y, POOP_W, POOP_H);
        }
        ctx.restore();
    }

    if (gameOver) {
        ctx.fillStyle = 'rgba(0,0,0,0.55)';
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        ctx.fillStyle = '#FFD700';
        ctx.font = 'bold 38px monospace';
        ctx.textAlign = 'center';
        ctx.textBaseline = 'middle';
        ctx.fillText('GAME OVER', canvas.width / 2, canvas.height / 2 - 24);
        ctx.fillStyle = '#fff';
        ctx.font = '18px monospace';
        ctx.fillText(t('pigeon.tap-replay'), canvas.width / 2, canvas.height / 2 + 24);
    }
}

