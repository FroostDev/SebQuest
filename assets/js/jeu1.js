let betaBase = null;

/**
 * Récupère l'inclinaison du téléphone depuis les capteurs.
 * Calibre la position neutre au premier appel, et attrape aussi
 * le cap compas pour la partie radar.
 * @param {DeviceOrientationEvent} e - L'événement d'orientation.
 */
function handleOrientation(e) {
    if (e.gamma === null) return;
    if (betaBase === null) betaBase = e.beta || 0;
    tiltX = e.gamma || 0;
    tiltY = (e.beta || 0) - betaBase;
    if (typeof e.webkitCompassHeading === 'number') {
        compassHeading = e.webkitCompassHeading;
    } else if (e.alpha !== null) {
        compassHeading = (360 - (e.alpha || 0)) % 360;
    }
}

/**
 * Active l'écoute des capteurs d'orientation une fois la permission obtenue.
 */
function listenOrientation() {
    window.addEventListener('deviceorientation', handleOrientation);
    window.addEventListener('deviceorientationabsolute', handleOrientation);
}

/**
 * Lance la partie : cache l'écran d'accueil et initialise le jeu.
 * Ne fait rien si la partie est déjà en cours.
 */
function startGame() {
    if (gameStarted) return;
    gameStarted = true;
    init();
    pigeonMusic = new Audio('../assets/sound/music/pigeon.mp3');
    pigeonMusic.volume = 0.4;
    pigeonMusic.loop = true;
    pigeonMusic.play().catch(() => { });
    document.getElementById('start-overlay').style.display = 'none';
    document.getElementById('pigeon-pause-btn').style.display = 'flex';
}

/**
 * Lâche un caca depuis le bas du pigeon.
 * Le projectile hérite d'une partie de la vitesse horizontale du pigeon.
 * Un cooldown de 800ms empêche de spammer.
 */
function shootPoop() {
    if (!gameStarted || gameOver) return;
    const now = Date.now();
    if (now - lastShot < SHOOT_COOLDOWN) return;
    lastShot = now;
    poops.push({
        x: pigeon.x + PIGEON_W / 2 - POOP_W / 2,
        y: pigeon.y + PIGEON_H,
        vx: pigeon.vx * 0.35,
        vy: 2.5
    });
    const sfx = new Audio('../assets/sound/sfx/poop.mp3');
    sfx.play().catch(() => { });
}

/**
 * Met à jour la barre de timer dans le SVG.
 * @param {number} ratio - Entre 0 et 1 (1 = plein, 0 = vide).
 */
function updateTimerBar(ratio) {
    const fill = document.getElementById('timer-fill');
    if (fill) fill.setAttribute('width', Math.max(0, ratio * TIMER_BAR_MAX_W).toFixed(1));
}

