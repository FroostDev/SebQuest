/**
 * Gère un tap sur le canvas radar selon l'état actuel :
 * rejouer le radar, ou retourner complètement au début.
 */
function handleRadarTap() {
    if (radarWin) {
        stopBeeps();
        stopGeo();
        radarPhase = false;
        radarCanvas.style.display = 'none';
        canvas.style.display = 'block';
        document.getElementById('radar-pause-btn').style.display = 'none';
        document.getElementById('radar-skip-target-btn').style.display = 'none';
        document.getElementById('radar-pause-menu').classList.remove('open');

        // Jouer la cinématique de fin, puis passer au niveau suivant (ou retour menu en dev mode)
        Cinematic.play(canvas, applyCineTexts(CINE_END, CINE_TEXTS[getLang()].end), () => {
            if (localStorage.getItem('devMode') === 'true') {
                localStorage.setItem('devMode', 'false');
                window.location.href = '../index.html';
            } else {
                const currentLevel = parseInt(localStorage.getItem('sebquest_level') || '0', 10);
                localStorage.setItem('sebquest_level', currentLevel + 1);
                window.location.href = '../pages/carte.html';
            }
        });
        return;
    }
    if (radarGameOver) {
        stopBeeps();
        stopGeo();
        radarTimerStart = Date.now();
        radarGameOver = false;
        radarWin = false;
        radarCollected = 0;
        radarCurrentTarget = 0;
        radarTargets = [];
        currentPos = null;
        geoError = null;
        lastBeepDist = 99999;
        updateTimerBar(1);
        document.getElementById('hp-fill').setAttribute('width', '0');
        if ('geolocation' in navigator) {
            watchId = navigator.geolocation.watchPosition(
                pos => {
                    currentPos = { lat: pos.coords.latitude, lng: pos.coords.longitude };
                    if (radarTargets.length === 0) radarTargets = generateRadarTargets(currentPos.lat, currentPos.lng);
                },
                err => { geoError = err.message; },
                { enableHighAccuracy: true, maximumAge: 0, timeout: 5000 }
            );
        }
        scheduleBeep();
    }
}

